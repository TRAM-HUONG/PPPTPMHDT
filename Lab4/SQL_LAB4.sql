DELETE FROM CHITIETDONHANG;
DELETE FROM DONHANG;
DELETE FROM GIOHANG;
DELETE FROM SANPHAM;
DELETE FROM NHOMSANPHAM;
DELETE FROM PHIEUDATHANG;
DELETE FROM KHACHHANG;
GO


