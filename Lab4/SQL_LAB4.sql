CREATE DATABASE E_SHOPPING;
GO

-- Sử dụng database vừa tạo
USE E_SHOPPING;
GO

-- =========================================================
-- 1. TẠO TOÀN BỘ CÁC BẢNG (FULL DATABASE)
-- =========================================================

-- 1.1. Bảng Khách hàng
CREATE TABLE KHACHHANG (
    MAKH VARCHAR(10) PRIMARY KEY,
    HOTEN VARCHAR(100) NOT NULL,
    NGAYSINH DATE,
    CCCD VARCHAR(20) UNIQUE NOT NULL,
    DIACHI VARCHAR(255),
    DIENTHOAI VARCHAR(15),
    TENDANGNHAP VARCHAR(50) UNIQUE NOT NULL,
    MATKHAU VARCHAR(255) NOT NULL,
    EMAIL VARCHAR(100) UNIQUE
);

-- 1.2. Bảng Nhóm sản phẩm
CREATE TABLE NHOMSANPHAM (
    MANHOM VARCHAR(10) PRIMARY KEY,
    TENNHOM VARCHAR(100) NOT NULL,
    MOTANHOM TEXT
);

-- 1.3. Bảng Sản phẩm
CREATE TABLE SANPHAM (
    MASP VARCHAR(20) PRIMARY KEY,
    TENSP VARCHAR(100) NOT NULL,
    NHASANXUAT VARCHAR(100),
    HINHANH VARCHAR(255),
    MOTASP TEXT,
    THONGSOKYTHUAT TEXT,
    GIABANHIENHANH DECIMAL(12,2) NOT NULL,
    TINHTRANG INT, 
    MANHOM VARCHAR(10),
    FOREIGN KEY (MANHOM) REFERENCES NHOMSANPHAM(MANHOM)
);

-- 1.4. Bảng Giỏ hàng
CREATE TABLE GIOHANG (
    MAKH VARCHAR(10),
    MASP VARCHAR(20),
    SOLUONG INT NOT NULL,
    PRIMARY KEY (MAKH, MASP),
    FOREIGN KEY (MAKH) REFERENCES KHACHHANG(MAKH) ON DELETE CASCADE,
    FOREIGN KEY (MASP) REFERENCES SANPHAM(MASP) ON DELETE CASCADE
);

-- 1.5. Bảng Loại phiếu đặt hàng
CREATE TABLE PHIEUDATHANG (
    MALOAIPHIEU VARCHAR(10) PRIMARY KEY,
    TENLOAIPHIEU VARCHAR(50) NOT NULL,
    DONGIPHIVANCHUYEN DECIMAL(12,2) NOT NULL,
    THOIGIANXULY VARCHAR(50)
);

-- 1.6. Bảng Đơn hàng
CREATE TABLE DONHANG (
    SODDH VARCHAR(20) PRIMARY KEY,
    NGAYDATHANG DATETIME NOT NULL,
    TONGTRIGIA DECIMAL(12,2) NOT NULL,
    PHIGIAOHANG DECIMAL(12,2) DEFAULT 0,
    TENNGUOINHAN VARCHAR(100) NOT NULL,
    DIACHINHAN VARCHAR(255) NOT NULL,
    DIENTHOAINHAN VARCHAR(15) NOT NULL,
    MAKH VARCHAR(10),
    MALOAIPHIEU VARCHAR(10),
    FOREIGN KEY (MAKH) REFERENCES KHACHHANG(MAKH),
    FOREIGN KEY (MALOAIPHIEU) REFERENCES PHIEUDATHANG(MALOAIPHIEU)
);

-- 1.7. Bảng Chi tiết đơn hàng
CREATE TABLE CHITIETDONHANG (
    SODDH VARCHAR(20),
    MASP VARCHAR(20),
    SOLUONG INT NOT NULL,
    DONGIA DECIMAL(12,2) NOT NULL,
    PRIMARY KEY (SODDH, MASP),
    FOREIGN KEY (SODDH) REFERENCES DONHANG(SODDH) ON DELETE CASCADE,
    FOREIGN KEY (MASP) REFERENCES SANPHAM(MASP)
);

-- 1.8. Bảng Thanh toán thẻ tín dụng
CREATE TABLE THANHTOANTHE (
    MAGIAODICH VARCHAR(20) PRIMARY KEY,
    SODDH VARCHAR(20) UNIQUE,
    LOAITHE VARCHAR(20) NOT NULL,
    SOHIEUTHE VARCHAR(20) NOT NULL,
    NGAYHETHAN VARCHAR(10) NOT NULL,
    HOTENCHUTHE VARCHAR(100) NOT NULL,
    MASOANNINHCSV VARCHAR(4) NOT NULL,
    TRANGTHAITHANHTOAN VARCHAR(50) NOT NULL,
    FOREIGN KEY (SODDH) REFERENCES DONHANG(SODDH) ON DELETE CASCADE
)

USE E_SHOPPING;
GO

-- Mở rộng độ dài cột TENLOAIPHIEU để chứa chuỗi dài không bị cắt cụt
ALTER TABLE PHIEUDATHANG ALTER COLUMN TENLOAIPHIEU NVARCHAR(200);
GO


